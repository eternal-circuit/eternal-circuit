#!/usr/bin/env python3
"""Eternal Circuit generation harness.

Turns scene cards and voice bibles into model prompts, calls the Anthropic
Messages API, writes the generated text, and appends a provenance record, as
required by AUTHORSHIP.md. Standard library only.

Usage (run from the repository root):

  # Scene variants from a card (one API call per variant)
  python3 studio/production/tools/generate.py variants \
      studio/production/the-genesis-protocol/proto-3/cards/ch01-s06-naming.md

  # Revision round: regenerate with author notes
  python3 studio/production/tools/generate.py variants CARD --notes notes.md

  # Voice-bible sample passages
  python3 studio/production/tools/generate.py samples the-genesis-protocol

Add --dry-run to write the prompts without calling the API, and --estimate to
print an approximate cost. The API key is read from ANTHROPIC_API_KEY.
"""

import argparse
import datetime as dt
import hashlib
import json
import os
import re
import subprocess
import sys
import urllib.error
import urllib.request
from pathlib import Path

API_URL = "https://api.anthropic.com/v1/messages"
API_VERSION = "2023-06-01"
DEFAULT_MODEL = "claude-fable-5-2"

# USD per million tokens (input, output). Checked 2026-11-23 on the Claude
# pricing page; update when prices change. Used only for --estimate.
PRICES = {
    "claude-fable-5-2": (8.0, 40.0),
    "claude-opus-5-5": (4.0, 20.0),
    "claude-sonnet-5-5": (2.0, 10.0),
}

REPO = Path(__file__).resolve().parents[3]
PRODUCTION = REPO / "studio" / "production"

SYSTEM_PROMPT = """You are the prose generator for The Eternal Circuit, a literary science fiction project.
Under the project's authorship rule, every word of published prose is generated by a model, and a human author directs, selects and arranges it.
Your job is to write exactly the passage requested, following the scene card, the voice bible and the story brief.

Rules:
- Output only the prose of the passage. No title, heading, preface, notes, or commentary.
- Follow the card's purpose, turn, withheld material and forbidden moves exactly. What is withheld must stay withheld.
- Homage seeds shape technique only. Never quote or closely imitate the seed author's sentences, characters, invented terms or plots.
- Never reproduce dialogue, subtitles, lyrics or text from any existing work, including works referenced in the scene.
- Avoid stock phrasing and any sentence that states the theme.
- Stay within about 10% of the word target."""


def read(path):
    return Path(path).read_text(encoding="utf-8")


def frontmatter(text):
    """Return (fields, body) for a simple '---' frontmatter block."""
    m = re.match(r"^---\n(.*?)\n---\n?(.*)$", text, re.S)
    if not m:
        return {}, text
    fields = {}
    for line in m.group(1).splitlines():
        if ":" in line:
            key, val = line.split(":", 1)
            fields[key.strip()] = val.split("#", 1)[0].strip().strip('"')
    return fields, m.group(2)


def section(body, name):
    m = re.search(rf"^## {re.escape(name)}\s*\n(.*?)(?=^## |\Z)", body, re.S | re.M)
    return m.group(1).strip() if m else ""


def divergences(body):
    """Bullet lines from the card's Divergence section."""
    return [re.sub(r"^[-*]\s*", "", line).strip()
            for line in section(body, "Divergence").splitlines()
            if re.match(r"^\s*[-*]\s+", line)]


def git_state():
    try:
        head = subprocess.check_output(["git", "-C", str(REPO), "rev-parse", "--short", "HEAD"],
                                       text=True).strip()
        dirty = subprocess.call(["git", "-C", str(REPO), "diff", "--quiet"]) != 0
        return head + ("+uncommitted" if dirty else "")
    except Exception:
        return "unknown"


def sha(text):
    return hashlib.sha256(text.encode("utf-8")).hexdigest()[:12]


def rel(path):
    return str(Path(path).resolve().relative_to(REPO))


def call_api(model, system, prompt, max_tokens):
    key = os.environ.get("ANTHROPIC_API_KEY")
    if not key:
        sys.exit("ANTHROPIC_API_KEY is not set. Use --dry-run to write prompts only.")
    payload = json.dumps({
        "model": model,
        "max_tokens": max_tokens,
        "system": system,
        "messages": [{"role": "user", "content": prompt}],
    }).encode("utf-8")
    req = urllib.request.Request(API_URL, data=payload, method="POST", headers={
        "x-api-key": key,
        "anthropic-version": API_VERSION,
        "content-type": "application/json",
    })
    try:
        with urllib.request.urlopen(req, timeout=600) as resp:
            data = json.load(resp)
    except urllib.error.HTTPError as e:
        sys.exit(f"API error {e.code}: {e.read().decode('utf-8', 'replace')}")
    text = "".join(block.get("text", "") for block in data.get("content", [])
                   if block.get("type") == "text")
    return text.strip(), data.get("usage", {})


def estimate(model, prompts, out_tokens_each):
    price_in, price_out = PRICES.get(model, (None, None))
    tokens_in = sum(len(p) // 4 for p in prompts)
    tokens_out = out_tokens_each * len(prompts)
    if price_in is None:
        return f"~{tokens_in:,} input and ~{tokens_out:,} output tokens (no price on file for {model})"
    cost = tokens_in / 1e6 * price_in + tokens_out / 1e6 * price_out
    return f"~{tokens_in:,} input, ~{tokens_out:,} output tokens, about ${cost:.2f} with {model}"


def story_dir_for(card_path):
    # cards live at studio/production/<story>/<draft>/cards/<id>.md
    return Path(card_path).resolve().parents[2]


def previous_scene_text(card_path, card_id, max_words=1500):
    """Selected text of the previous scene in the same chapter, if any."""
    cards = sorted(Path(card_path).resolve().parent.glob("*.md"))
    names = [c.name for c in cards]
    idx = names.index(Path(card_path).name)
    if idx == 0:
        return ""
    prev_fields, _ = frontmatter(read(cards[idx - 1]))
    chosen = prev_fields.get("chosen", "").split(",")[0].strip()
    if not chosen:
        return ""
    variant = Path(card_path).resolve().parents[1] / "variants" / f"{chosen}.md"
    if not variant.exists():
        return ""
    words = read(variant).split()
    return " ".join(words[-max_words:])


def build_variant_prompt(card_path, extra_context, notes, divergence):
    story = story_dir_for(card_path)
    draft = Path(card_path).resolve().parents[1]
    fields, body = frontmatter(read(card_path))
    parts = [
        "# Voice bible\n\n" + read(story / "VOICE.md"),
        "# Story brief\n\n" + read(draft / "BRIEF.md"),
        "# Glossary\n\n" + read(REPO / "studio" / "canon" / "GLOSSARY.md"),
    ]
    if (story / "SETTING.md").exists():
        parts.insert(1, "# Setting bible\n\n" + read(story / "SETTING.md"))
    for path in extra_context:
        parts.append(f"# Context: {path}\n\n" + read(REPO / path))
    prev = previous_scene_text(card_path, fields.get("id", ""))
    if prev:
        parts.append("# End of the previous scene (selected text)\n\n" + prev)
    parts.append("# Scene card\n\n" + read(card_path))
    if notes:
        parts.append("# Author's revision notes for this round\n\n" + notes)
    target = fields.get("word_target", "")
    instruction = f"Write scene {fields.get('id', '')}, about {target} words."
    if divergence:
        instruction += f" This variant's divergence: {divergence}"
    parts.append("# Task\n\n" + instruction)
    return "\n\n---\n\n".join(parts), int(target or 800)


def next_round(log_path):
    if not log_path.exists():
        return 1
    return len(re.findall(r"^## Round ", read(log_path), re.M)) + 1


def next_variant_number(variants_dir, card_id):
    nums = [int(m.group(1)) for p in variants_dir.glob(f"{card_id}-v*.md")
            if (m := re.search(r"-v(\d+)\.md$", p.name))]
    return max(nums, default=0) + 1


def cmd_variants(args):
    card = Path(args.card)
    fields, body = frontmatter(read(card))
    card_id = fields.get("id") or card.stem
    draft = card.resolve().parents[1]
    variants_dir, prompts_dir, log_dir = (draft / d for d in ("variants", "prompts", "log"))
    notes = read(args.notes) if args.notes else ""

    divs = divergences(body)
    n = args.n or int(fields.get("variants_requested") or 3)
    plan = [divs[i % len(divs)] if divs else "" for i in range(n)]

    round_no = next_round(log_dir / f"{card_id}.md")
    first_v = next_variant_number(variants_dir, card_id)
    prompts = []
    for i, div in enumerate(plan):
        prompt, words = build_variant_prompt(card, args.context, notes, div)
        prompts.append((first_v + i, div, prompt, words))

    out_tokens = max(p[3] for p in prompts) * 2 + 500
    print(estimate(args.model, [p[2] for p in prompts], out_tokens))
    if args.estimate:
        return

    for d in (variants_dir, prompts_dir, log_dir):
        d.mkdir(parents=True, exist_ok=True)
    state = git_state()
    today = dt.date.today().isoformat()
    entries = []
    for vnum, div, prompt, _ in prompts:
        vid = f"{card_id}-v{vnum}"
        prompt_file = prompts_dir / f"{vid}.prompt.md"
        prompt_file.write_text(f"<!-- system prompt sha {sha(SYSTEM_PROMPT)} -->\n\n{prompt}\n",
                               encoding="utf-8")
        if args.dry_run:
            print(f"[dry run] wrote {rel(prompt_file)}")
            continue
        text, usage = call_api(args.model, SYSTEM_PROMPT, prompt, out_tokens)
        (variants_dir / f"{vid}.md").write_text(text + "\n", encoding="utf-8")
        words = len(text.split())
        print(f"wrote {rel(variants_dir / (vid + '.md'))} ({words} words, usage {usage})")
        entries.append(f"  - **{vid}** — {div or 'no divergence given'} · {words} words · "
                       f"prompt `{rel(prompt_file)}` (sha {sha(prompt)}) · usage {json.dumps(usage)}")

    if args.dry_run or not entries:
        return
    log_path = log_dir / f"{card_id}.md"
    if not log_path.exists():
        log_path.write_text(f"---\nscene: {card_id}\n---\n", encoding="utf-8")
    with open(log_path, "a", encoding="utf-8") as f:
        f.write(f"\n## Round {round_no} — {today}\n\n"
                f"- **Model:** {args.model}\n"
                f"- **Repository state:** {state}\n"
                f"- **Inputs:** card `{rel(card)}`, VOICE.md, SETTING.md (if present), BRIEF.md, GLOSSARY.md"
                + "".join(f", `{c}`" for c in args.context) + "\n"
                + (f"- **Author notes:** `{args.notes}` (sha {sha(notes)})\n" if notes else "")
                + "- **Variants:**\n" + "\n".join(entries) + "\n"
                "- **Decision:** _pending — record the author's choice, arrangement and notes here_\n")
    print(f"logged round {round_no} in {rel(log_path)}")


DEFAULT_REGISTERS = [
    "domestic comedy: two partners bickering affectionately over something small",
    "a generated system summary that is fluent, plausible and subtly wrong",
    "Rachel alone at a threshold, deciding whether to cross it",
    "Daniel at work, describing a fault in engineering language while avoiding the real problem",
    "a short paranoid loop of thought that repeats and second-guesses itself",
    "grief surfacing without warning inside an ordinary task",
    "Tom answering a direct question with a precise, narrow truth",
    "Megan deflecting with a joke, then saying one true thing",
    "a register header and a one-line keeper annotation, in the archive's voice",
    "a bureaucratic form or ticket rendered with deadpan horror",
    "a long run-on sentence of anxious thought set against a flat procedural line",
    "the house at night: quiet, slightly too attentive",
    "an argument conducted entirely in technically true statements",
    "Rachel asking one blunt literal question and waiting",
    "the farm in Iowa: physical work, a machine that is allowed to fail",
]


def cmd_samples(args):
    story = PRODUCTION / args.story
    voice = read(story / "VOICE.md")
    registers = ([l.strip() for l in read(args.registers).splitlines() if l.strip()]
                 if args.registers else DEFAULT_REGISTERS)[: args.n]
    samples_dir = story / "samples"
    existing = [int(m.group(1)) for p in samples_dir.glob("round-*")
                if (m := re.match(r"round-(\d+)", p.name))]
    round_dir = samples_dir / f"round-{max(existing, default=0) + 1:02d}"

    prompts = []
    for reg in registers:
        prompts.append("# Voice bible\n\n" + voice +
                       "\n\n---\n\n# Task\n\nWrite one original passage of 150–250 words in this "
                       f"story's voice. Register: {reg}. Use the story's characters and world, "
                       "but invent a moment that is not in any draft. This is a voice sample, "
                       "not a scene for the book.")
    print(estimate(args.model, prompts, 600))
    if args.estimate:
        return
    round_dir.mkdir(parents=True, exist_ok=True)
    log = [f"# Voice samples — {round_dir.name}\n",
           f"- **Model:** {args.model}",
           f"- **Repository state:** {git_state()}",
           f"- **Date:** {dt.date.today().isoformat()}",
           "- **Author picks:** _pending_\n"]
    for i, (reg, prompt) in enumerate(zip(registers, prompts), 1):
        slug = "-".join(re.findall(r"[a-z0-9]+", reg.split(":")[0].lower())[:4])
        base = round_dir / f"sample-{i:02d}-{slug}"
        Path(f"{base}.prompt.md").write_text(prompt + "\n", encoding="utf-8")
        if args.dry_run:
            print(f"[dry run] wrote {rel(str(base) + '.prompt.md')}")
            continue
        text, usage = call_api(args.model, SYSTEM_PROMPT, prompt, 700)
        Path(f"{base}.md").write_text(f"*Register: {reg}*\n\n{text}\n", encoding="utf-8")
        log.append(f"- `{base.name}.md` — {reg} · usage {json.dumps(usage)}")
        print(f"wrote {rel(str(base) + '.md')}")
    if not args.dry_run:
        (round_dir / "LOG.md").write_text("\n".join(log) + "\n", encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="cmd", required=True)
    for name in ("variants", "samples"):
        p = sub.add_parser(name)
        p.add_argument("--model", default=DEFAULT_MODEL)
        p.add_argument("--dry-run", action="store_true", help="write prompts, skip the API")
        p.add_argument("--estimate", action="store_true", help="print a cost estimate and stop")
        if name == "variants":
            p.add_argument("card")
            p.add_argument("--n", type=int, help="number of variants (default: card's request)")
            p.add_argument("--notes", help="file of author revision notes for this round")
            p.add_argument("--context", action="append", default=[],
                           help="extra repository file to include (repeatable)")
            p.set_defaults(func=cmd_variants)
        else:
            p.add_argument("story", help="story folder under studio/production/")
            p.add_argument("--n", type=int, default=15)
            p.add_argument("--registers", help="file with one register per line")
            p.set_defaults(func=cmd_samples)
    args = parser.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()
